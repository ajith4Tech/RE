// Copies the display fonts and the Noto font subsets for every supported script into public/fonts/
// and writes public/css/fonts-intl.css. Run after `npm install` if you add a script:
//   node tools/build-fonts.mjs
// The browser only downloads a file when the page actually shows that script
// (unicode-range), so phones reading English never download Tamil, etc.
import { readFile, writeFile, copyFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const SOURCES = [
  // [package, subset, family used in CSS, weights]
  ["barlow-condensed", "latin", "Signage", [600, 700, 800]], // highway-sign display face
  ["kalam", "latin", "Painted", [700]], // hand-painted roadside boards
  ["noto-sans-devanagari", "devanagari", "RideDeva", [400, 700]], // Hindi, Marathi, Nepali
  ["noto-sans-telugu", "telugu", "RideTelu", [400, 700]],
  ["noto-sans-bengali", "bengali", "RideBeng", [400, 700]], // Bengali, Assamese
  ["noto-sans-tamil", "tamil", "RideTaml", [400, 700]],
  ["noto-sans-kannada", "kannada", "RideKnda", [400, 700]],
  ["noto-serif-tibetan", "tibetan", "RideTibt", [400, 700]], // Ladakhi
  ["noto-nastaliq-urdu", "arabic", "RideUrdu", [400, 700]], // Urdu (Nastaliq)
];

await mkdir(root + "public/fonts", { recursive: true });
let css = `/* Generated by tools/build-fonts.mjs. Noto fonts, SIL Open Font License. */\n`;
for (const [pkg, subset, family, weights] of SOURCES) {
  for (const w of weights) {
    const srcCss = await readFile(`${root}node_modules/@fontsource/${pkg}/${w}.css`, "utf8");
    const file = `${pkg}-${subset}-${w}-normal.woff2`;
    const block = srcCss.split("@font-face").find((b) => b.includes(file));
    const range = block.match(/unicode-range:\s*([^;]+);/)[1].trim();
    await copyFile(`${root}node_modules/@fontsource/${pkg}/files/${file}`, `${root}public/fonts/${file}`);
    css += `@font-face { font-family: "${family}"; font-weight: ${w}; font-display: swap; src: url("../fonts/${file}") format("woff2"); unicode-range: ${range}; }\n`;
  }
  try {
    await copyFile(`${root}node_modules/@fontsource/${pkg}/LICENSE`, `${root}public/fonts/LICENSE-${pkg}.txt`);
  } catch {}
}
await writeFile(root + "public/css/fonts-intl.css", css);
console.log("Wrote public/css/fonts-intl.css");
